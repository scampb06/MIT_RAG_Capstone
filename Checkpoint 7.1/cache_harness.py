r"""Checkpoint 7.1: test harness for the semantic answer cache.

Three steps, cheapest first:

    python cache_harness.py --simulate     offline: hit rate of each eviction policy
                                           (LFU + aging, plain LFU, LRU, Lab 7.2's FIFO) on a
                                           synthetic workload with a popularity shift
    python cache_harness.py --calibrate    embeddings only (a fraction of a cent): how similar
                                           repeats, paraphrases and near-misses are to their
                                           originals, to choose the threshold
    python cache_harness.py --live         the tuned agent with a fresh cache on
                                           cache_workload.json: hits, wrong hits, latency and
                                           cost of a hit vs a miss (~$0.25)

Each step writes its results to evaluation_results/ (cache_*.json and cache_report.md).
The unit tests of the cache itself are `python semantic_cache.py --self-check`.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import statistics as st
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Any

import numpy as np

HERE = Path(__file__).parent
RESULTS = HERE / "evaluation_results"
WORKLOAD = HERE / "cache_workload.json"
REPORT = RESULTS / "cache_report.md"

_spec = importlib.util.spec_from_file_location("agent7_tuned", HERE / "capstone_checkpoint_7_1_tuned.py")
tuned = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = tuned
_spec.loader.exec_module(tuned)
semantic_cache, m71, m51, adv = tuned.semantic_cache, tuned.m71, tuned.m51, tuned.adv


def load_workload() -> list[dict[str, Any]]:
    return json.loads(WORKLOAD.read_text(encoding="utf-8"))["requests"]


def write_section(name: str, lines: list[str]) -> None:
    """Keep one section per step in cache_report.md, replacing an earlier version of it."""
    sections: dict[str, str] = {}
    if REPORT.is_file():
        current = None
        for line in REPORT.read_text(encoding="utf-8").splitlines():
            if line.startswith("## "):
                current = line[3:].split(":")[0]
                sections[current] = line + "\n"
            elif current:
                sections[current] += line + "\n"
    sections[name] = "\n".join(lines) + "\n"
    order = ["Eviction policies", "Threshold calibration", "Live workload"]
    body = "".join(sections[key] + "\n" for key in order if key in sections)
    REPORT.write_text("# Checkpoint 7.1: semantic cache evidence\n\nGenerated by `cache_harness.py`.\n\n" + body,
                      encoding="utf-8")


# %%
def run_simulation() -> None:
    rows = semantic_cache.simulate()
    sizes = sorted({row["cache_size"] for row in rows})
    lines = ["## Eviction policies: offline simulation (no model calls)", "",
             "20,000 requests over 600 question topics with Zipf-like popularity (each request a random "
             "paraphrase of its topic); halfway through, popularity shifts to other topics. Fake "
             "embeddings; threshold 0.90; half-life 500 lookups; grace 10 lookups.", "",
             "| Cache size | " + " | ".join(semantic_cache.POLICIES) + " |", "|---|" + "---|" * len(semantic_cache.POLICIES)]
    for size in sizes:
        rates = {row["policy"]: row["hit_rate"] for row in rows if row["cache_size"] == size}
        lines.append(f"| {size} | " + " | ".join(f"{rates[p]:.1%}" for p in semantic_cache.POLICIES) + " |")
    lines += ["", "`fifo` is Lab 7.2's policy (evict the oldest entry). `lfu` without aging keeps old "
                  "favourites and evicts every new entry first, which is why it trails `lru`."]
    (RESULTS / "cache_simulation.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    write_section("Eviction policies", lines)
    print("\n".join(lines))


# %%
def run_calibration() -> None:
    requests = load_workload()
    embeddings = adv.get_embeddings()
    vectors = {r["id"]: np.asarray(embeddings.embed_query(r["question"])) for r in requests}
    unit = {key: value / np.linalg.norm(value) for key, value in vectors.items()}
    rows = []
    for request in requests:
        if request["kind"] == "original":
            continue
        similarity = float(unit[request["id"]] @ unit[request["of"]])
        original = next(r["question"] for r in requests if r["id"] == request["of"])
        guarded = semantic_cache.numbers_in(request["question"]) != semantic_cache.numbers_in(original)
        rows.append({"id": request["id"], "kind": request["kind"], "change": request.get("change"),
                     "similarity": round(similarity, 4), "number_guard_blocks": guarded,
                     "question": request["question"], "original": original})
    reuse = [r["similarity"] for r in rows if r["kind"] in ("repeat", "paraphrase")]
    paraphrases = [r["similarity"] for r in rows if r["kind"] == "paraphrase"]
    unguarded_near = [r["similarity"] for r in rows if r["kind"] == "near_miss" and not r["number_guard_blocks"]]
    lines = ["## Threshold calibration: text-embedding-3-small similarities to the original question", "",
             "| Request | Kind | Change | Similarity | Number guard blocks it | Question |", "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["kind"], -r["similarity"])):
        lines.append(f"| {r['id']} | {r['kind']} | {r['change'] or ''} | {r['similarity']:.3f} | "
                     f"{'yes' if r['number_guard_blocks'] else ''} | {r['question']} |")
    lowest_paraphrase, highest_near = min(paraphrases), max(unguarded_near) if unguarded_near else 0.0
    lines += ["", f"- Paraphrases: {min(paraphrases):.3f}–{max(paraphrases):.3f} (mean {st.mean(paraphrases):.3f}).",
              f"- Near-misses the number guard does not catch: {min(unguarded_near):.3f}–{highest_near:.3f}."]
    if lowest_paraphrase > highest_near:
        threshold = round((lowest_paraphrase + highest_near) / 2, 3)
        lines.append(f"- **The ranges do not overlap**: any threshold in ({highest_near:.3f}, {lowest_paraphrase:.3f}) "
                     f"serves every paraphrase and no near-miss; the midpoint is {threshold}.")
    else:
        above = [s for s in paraphrases if s > highest_near]
        threshold = round((highest_near + min(above)) / 2, 3) if above else 0.99
        served = sum(s >= threshold for s in paraphrases)
        lines.append(f"- **The ranges overlap**: no threshold serves every paraphrase and blocks every near-miss. A wrong "
                     f"cached answer is worse than a miss, so the threshold must sit above the highest near-miss "
                     f"({highest_near:.3f}); it is set at the midpoint of the gap between that and the lowest paraphrase "
                     f"above it ({min(above) if above else 0:.3f}), **{threshold}**, which serves {served} of "
                     f"{len(paraphrases)} paraphrases. At the earlier default of 0.90, "
                     f"{sum(s >= 0.90 for s in unguarded_near)} near-miss(es) would have been served a wrong answer.")
    (RESULTS / "cache_calibration.json").write_text(json.dumps({"threshold": threshold, "rows": rows}, indent=1), encoding="utf-8")
    write_section("Threshold calibration", lines)
    print("\n".join(lines))


