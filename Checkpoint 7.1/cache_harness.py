def run_live(threshold: float | None) -> None:
    if threshold is None:
        calibration = RESULTS / "cache_calibration.json"
        threshold = json.loads(calibration.read_text(encoding="utf-8"))["threshold"] if calibration.is_file() else 0.90
    requests = load_workload()
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    cache = tuned.make_cache(RESULTS / f"cache_live_{stamp}.json", threshold=threshold, max_size=400)
    m51.LOG_PATH = m71.LOG_PATH
    llm = adv.make_llm()
    agent = tuned.TunedAgent(llm, tuned.make_toolbox(set()), cache=cache)
    answers: dict[str, str] = {}
    rows = []
    for request in requests:
        started = time.perf_counter()
        state = agent.run(request["question"])
        seconds = time.perf_counter() - started
        info = state.get("cache") or {}
        hit = bool(info.get("hit"))
        expected_hit = request["kind"] in ("repeat", "paraphrase")
        served_from = None
        if hit:
            served_from = next((r["id"] for r in requests if r["question"] == info.get("cached_question")), None)
        rows.append({"id": request["id"], "kind": request["kind"], "change": request.get("change"),
                     "question": request["question"], "hit": hit, "expected_hit": expected_hit,
                     "similarity": info.get("similarity"), "served_from": served_from,
                     "wrong_hit": hit and (request["kind"] == "near_miss" or (served_from and served_from != request.get("of"))),
                     "seconds": round(seconds, 2), "agent_cost_usd": m51._usage_cost(state["usage"]),
                     "model_calls": len(state["usage"]), "stop_reason": state["stop_reason"],
                     "response": state["response"][:400]})
        answers[request["id"]] = state["response"]
        print(f"{request['id']:3} {request['kind']:10} hit={hit!s:5} sim={info.get('similarity')} {seconds:5.1f}s "
              f"calls={len(state['usage'])} | {request['question'][:70]}")
    cache.save()
    hits, misses = [r for r in rows if r["hit"]], [r for r in rows if not r["hit"]]
    def mean(values):
        values = [v for v in values if v is not None]
        return st.mean(values) if values else 0.0
    reuse = [r for r in rows if r["expected_hit"]]
    lines = [f"## Live workload: tuned agent (gpt-5.4-mini) with a fresh cache, threshold {threshold}", "",
             f"{len(rows)} requests from `cache_workload.json`, in order: 8 originals, then repeats, paraphrases "
             "and near-misses. LFU with aging, 400 entries.", "",
             "| | Requests | Served from cache |", "|---|---|---|"]
    for kind in ("original", "repeat", "paraphrase", "near_miss"):
        group = [r for r in rows if r["kind"] == kind]
        lines.append(f"| {kind} | {len(group)} | {sum(r['hit'] for r in group)} |")
    lines += ["", "| Measure | Cache hit | Cache miss (full agent) |", "|---|---|---|",
              f"| Requests | {len(hits)} | {len(misses)} |",
              f"| Latency, mean | {mean([r['seconds'] for r in hits]):.2f} s | {mean([r['seconds'] for r in misses]):.1f} s |",
              f"| Agent cost per request | ${mean([r['agent_cost_usd'] for r in hits]):.5f} | ${mean([r['agent_cost_usd'] for r in misses]):.4f} |",
              f"| Model calls per request | {mean([r['model_calls'] for r in hits]):.1f} | {mean([r['model_calls'] for r in misses]):.1f} |",
              "", f"- **Reuse served:** {sum(r['hit'] for r in reuse)} of {len(reuse)} repeats and paraphrases.",
              f"- **Wrong hits:** {sum(bool(r['wrong_hit']) for r in rows)} (a near-miss, or a request served another "
              "question's answer). This must be 0.",
              f"- **Cost avoided:** {len(hits)} hits × ${mean([r['agent_cost_usd'] for r in misses]):.4f} average miss = "
              f"${len(hits) * mean([r['agent_cost_usd'] for r in misses]):.4f} on this workload "
              f"({len(hits) / len(rows):.0%} of requests).",
              f"- Cache statistics: `{json.dumps({k: v for k, v in cache.stats().items() if k != 'top_entries'})}`", "",
              "| Request | Kind | Hit | Similarity | Latency | Question |", "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['id']} | {r['kind']} | {'yes' if r['hit'] else ''}{' ⚠ WRONG' if r['wrong_hit'] else ''} | "
                     f"{r['similarity'] if r['similarity'] is not None else ''} | {r['seconds']} s | {r['question']} |")
    (RESULTS / f"cache_live_results_{stamp}.json").write_text(json.dumps({"threshold": threshold, "rows": rows,
                                                                          "stats": cache.stats()}, indent=1), encoding="utf-8")
    write_section("Live workload", lines)
    print("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description="Semantic cache test harness (Checkpoint 7.1).")
    parser.add_argument("--simulate", action="store_true")
    parser.add_argument("--calibrate", action="store_true")
    parser.add_argument("--live", action="store_true")
    parser.add_argument("--threshold", type=float, help="live: override the calibrated threshold")
    args = parser.parse_args()
    if args.simulate:
        run_simulation()
    if args.calibrate:
        run_calibration()
    if args.live:
        run_live(args.threshold)


if __name__ == "__main__":
    main()
